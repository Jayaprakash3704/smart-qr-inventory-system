def build_manual(
    output: str,
    company_name: str,
    prepared_by: str,
    version: str,
    app_name: str,
) -> None:
    doc = Document()
    configure_page(doc)
    set_default_font(doc)

    generated_on = datetime.now().strftime("%d %B %Y")

    add_cover_page(doc, company_name, prepared_by, version, app_name, generated_on)
    add_table_of_contents(doc)
    add_purpose_section(doc, app_name)
    add_overview_section(doc, app_name)
    add_navigation_section(doc)
    add_workflow_section(doc)
    add_module_steps_section(doc)
    add_do_not_modify_section(doc)
    add_settings_and_reports(doc)
    add_troubleshooting(doc)
    add_data_security_support(doc)

    doc.save(output)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate a professional DOCX user manual for the Yarn Roll Tracker desktop application."
    )
    parser.add_argument(
        "--output",
        default="Yarn_Roll_Tracker_User_Manual.docx",
        help="Output DOCX file path",
    )
    parser.add_argument(
        "--company",
        default="Client Company",
        help="Company name displayed on the cover page",
    )
    parser.add_argument(
        "--prepared-by",
        default="Implementation Team",
        help="Prepared-by value on the cover page",
    )
    parser.add_argument(
        "--version",
        default="1.0",
        help="Document version",
    )
    parser.add_argument(
        "--app-name",
        default="Yarn Roll Tracking System",
        help="Application name to show in the manual",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    build_manual(
        output=args.output,
        company_name=args.company,
        prepared_by=args.prepared_by,
        version=args.version,
        app_name=args.app_name,
    )
    print(f"User manual created successfully: {args.output}")


if __name__ == "__main__":
    main()
