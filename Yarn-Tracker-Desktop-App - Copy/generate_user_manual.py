from __future__ import annotations

import argparse
from datetime import datetime

from docx import Document
from docx.enum.section import WD_ORIENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor


def configure_page(doc: Document) -> None:
    section = doc.sections[0]
    section.page_width = Inches(8.27)   # A4 portrait
    section.page_height = Inches(11.69)
    section.left_margin = Inches(0.9)
    section.right_margin = Inches(0.9)
    section.top_margin = Inches(0.8)
    section.bottom_margin = Inches(0.8)
    section.orientation = WD_ORIENT.PORTRAIT


def set_default_font(doc: Document, font_name: str = "Calibri", size: int = 11) -> None:
    normal = doc.styles["Normal"]
    normal.font.name = font_name
    normal.font.size = Pt(size)
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), font_name)


def add_cover_page(
    doc: Document,
    company_name: str,
    prepared_by: str,
    version: str,
    app_name: str,
    generated_on: str,
) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER

    run = p.add_run(company_name)
    run.bold = True
    run.font.size = Pt(24)
    run.font.color.rgb = RGBColor(31, 41, 55)

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = subtitle.add_run(f"User Manual for {app_name}")
    run.bold = True
    run.font.size = Pt(18)
    run.font.color.rgb = RGBColor(17, 24, 39)

    doc.add_paragraph()

    meta = doc.add_table(rows=5, cols=2)
    meta.style = "Table Grid"
    meta.cell(0, 0).text = "Document Title"
    meta.cell(0, 1).text = f"{app_name} - End User Manual"
    meta.cell(1, 0).text = "Version"
    meta.cell(1, 1).text = version
    meta.cell(2, 0).text = "Prepared For"
    meta.cell(2, 1).text = company_name
    meta.cell(3, 0).text = "Prepared By"
    meta.cell(3, 1).text = prepared_by
    meta.cell(4, 0).text = "Date"
    meta.cell(4, 1).text = generated_on

    for row in meta.rows:
        for idx, cell in enumerate(row.cells):
            for par in cell.paragraphs:
                for r in par.runs:
                    if idx == 0:
                        r.bold = True

    doc.add_paragraph()
    note = doc.add_paragraph(
        "Confidential: This document is intended for authorized client personnel and operational teams only."
    )
    note.alignment = WD_ALIGN_PARAGRAPH.CENTER
    note.runs[0].italic = True

    doc.add_page_break()


def add_heading(doc: Document, text: str, level: int = 1) -> None:
    h = doc.add_heading(text, level=level)
    if h.runs:
        h.runs[0].font.color.rgb = RGBColor(17, 24, 39)


def add_bullet_points(doc: Document, items: list[str]) -> None:
    for item in items:
        p = doc.add_paragraph(item, style="List Bullet")
        p.paragraph_format.space_after = Pt(3)


def add_numbered_steps(doc: Document, steps: list[str]) -> None:
    for step in steps:
        p = doc.add_paragraph(step, style="List Number")
        p.paragraph_format.space_after = Pt(4)


